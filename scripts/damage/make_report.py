"""Write docs/damage_model.md from the simulator (tables are generated, not typed).

    python3 scripts/damage/make_report.py
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import f35_damage as d  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, "docs", "damage_model.md")


def kt_to_mach_sl(kt):
    return kt * 0.514444 / 340.29


def fmt(v, nd=2):
    if v is None:
        return "–"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def affects(comp, c):
    out = []
    if c.get("lift"):
        part, sd = c["lift"]
        share = (d.ROOT_SHARE if part == "root" else d.OUTER_SHARE) * d.PANEL_LIFT
        arm = d.ROOT_ARM if part == "root" else d.OUTER_ARM
        out.append(f"lift {share * 100:.0f} % of total at {arm:.2f} m arm → roll asymmetry, CLmax, induced drag")
    if c.get("roll"):
        kind, _ = c["roll"]
        out.append(f"roll control {d.ROLL_POWER[kind] / sum(2 * v for v in d.ROLL_POWER.values()) * 100:.0f} % of total")
    if c.get("pitch"):
        out.append(f"pitch authority {c['pitch'] * 100:.0f} % → g-limit")
    if c.get("yaw"):
        out.append("directional stability (Cnβ) → AoA limit")
    if c.get("thrust_core"):
        out.append("thrust ∝ health^1.2, flame-out below 15 %")
    if c.get("thrust_nozzle"):
        out.append("thrust −20 % at 0, afterburner lost below 50 %")
    if c.get("airflow"):
        out.append("engine airflow (half each) → thrust")
    if c.get("fuel"):
        tank, cap = c["fuel"]
        out.append(f"fuel tank '{tank}' ({d.FUEL_TANKS[tank]:.0f} kg): leaks when hit, lost if the part breaks off")
    if c.get("structure"):
        out.append(f"structural g / Mach limit (weight {c['structure']:.2f})")
    if c.get("q_limit"):
        out.append(f"max dynamic pressure ×{c['q_limit']:.2f} when destroyed")
    if c.get("mach_limit"):
        out.append(f"Mach placard {c['mach_limit']:.2f} when missing")
    if c.get("clmax"):
        out.append(f"CLmax −{c['clmax'] / 2:.2f}")
    if c.get("drag"):
        out.append(f"drag +{c['drag'] * 1e4:.0f} counts when destroyed")
    if c.get("mass"):
        out.append(f"{c['mass']:.0f} kg lost if it breaks off")
    for s in c.get("systems", []):
        out.append(f"system: {s}")
    if comp.startswith("main_gear") or comp == "nose_gear":
        ga = d.GROUND_ATTITUDE.get(comp)
        if ga:
            out.append(f"collapse on the ground: roll {ga['roll_deg']:+.1f}°, pitch {ga['pitch_deg']:+.1f}°")
    return "; ".join(out)


def main():
    d.load_model_data()
    d.calibrate()
    with open(d.JSON_PATH) as f:
        data = json.load(f)
    hb = {k: v.get("hitbox") for k, v in data["components"].items()}
    L = []
    w = L.append
    w("# F-35I \"Adir\" damage model")
    w("")
    w("*Generated by `scripts/damage/make_report.py` from `scripts/damage/f35_damage.py` and the hitboxes "
      "measured on the Blender model (`data/damage_model.json`). Do not edit by hand.*")
    w("")
    w("The model is destructible at three levels:")
    w("")
    w("1. **Hitboxes.** 30 damage components, each with hit points and an oriented box fitted to the "
      "Blender geometry (`HB_<component>` wire boxes in the *Hitboxes* collection, hidden in renders).")
    w("2. **Damage state.** Health 0..1 per component, stored as `health_<component>` on the `F35I_Rig` "
      "object, so it can be keyframed. Hits (point, ray, blast) are turned into health loss through the hitboxes.")
    w("3. **Effects.** `evaluate(state, Mach, altitude)` computes the flight attributes for a damage state. "
      "In Blender the same health values drive what you see: soot, impact scorches, smoke, fuel vapour, "
      "parts breaking off and tumbling away, a gear leg folding.")
    w("")
    w("All reference values come from public sources (see `docs/research.md`). Where the real figure is "
      "not public, the value is a typical fighter value and is marked **model**. The transonic drag rise "
      f"is calibrated so the intact jet just reaches Mach 1.6 at 11 km (calibrated peak CD0 = {d.CAL['cd0_peak']:.4f}).")
    w("")
    # ------------------------------------------------------------ intact
    it = d.evaluate(d.intact_state())
    S = d.SPEC
    w("## 1. Intact aircraft (default attributes)")
    w("")
    w("Reference condition: 60 % internal fuel, 2 × AIM-120 + 2 × GBU-31 internal, Mach 0.8 at 6 km.")
    w("")
    w("| Attribute | Value | Source |")
    w("|---|---|---|")
    rows = [
        ("Length / span / height", f"{S['length_m']} m / {S['span_m']} m / {S['height_m']} m", "official"),
        ("Wing area", f"{S['wing_area_m2']} m²", "official"),
        ("Empty mass / internal fuel", f"{S['empty_kg']:.0f} kg / {S['internal_fuel_kg']:.0f} kg", "official"),
        ("Reference mass", f"{it['mass_kg']} kg", "60 % fuel + stores"),
        ("Thrust, dry / afterburner (SL)", f"{S['thrust_dry_kN']:.0f} kN / {S['thrust_ab_kN']:.0f} kN", "official (F135)"),
        ("Thrust-to-weight (A/B)", fmt(it["thrust_to_weight"], 3), "computed"),
        ("Max Mach at 11 km", f"{it['max_mach_11km']} ({it['max_mach_11km_limited_by']})", "official limit"),
        ("Max speed at 11 km", f"{it['max_speed_kmh_11km']} km/h", "computed"),
        ("Max Mach at sea level", f"{it['max_mach_SL']} ({it['max_mach_SL_limited_by']}, {S['vmax_kcas']:.0f} KCAS)", "public / computed"),
        ("Max Mach at 11 km without afterburner", fmt(it["max_mach_dry_11km"], 3), "model"),
        ("g limits", f"+{S['g_max']:.0f} / {S['g_min']:.0f} g", "official"),
        ("AoA limit", f"{S['aoa_max_deg']:.0f}°", "public"),
        ("Service ceiling", f"{S['ceiling_m']:.0f} m", "official"),
        ("CLmax / stall speed (SL, ref. mass)", f"{it['cl_max']} / {it['stall_speed_kt_SL']} kt", "model"),
        ("Max roll rate at M0.8 / 6 km", f"{it['max_roll_rate_deg_s']}°/s", "model"),
        ("Directional stability Cnβ", f"{it['cn_beta_per_rad']} /rad", "model"),
        ("Cruise fuel burn at M0.8 / 6 km", f"{it['fuel_burn_kg_min']} kg/min", "model"),
        ("Endurance at that condition (90 % of fuel)", f"{it['endurance_min']} min", "model"),
        ("Bank needed to fly straight", f"{it['tilt_bank_deg']}°", "computed"),
    ]
    for r in rows:
        w(f"| {r[0]} | {r[1]} | {r[2]} |")
    w("")
    w("Model assumptions (not public): lift-curve slope "
      f"{S['cl_alpha_per_rad']}/rad, CLmax {S['cl_max']}, subsonic CD0 {S['cd0_sub']}, induced-drag factor "
      f"{S['k_induced_sub']}, roll damping Clp {S['clp']}, dihedral effect Clβ {S['cl_beta']}/rad, side force "
      f"CYβ {S['cy_beta']}/rad, max trim sideslip {S['beta_max_deg']}°, the flight control system keeps "
      f"{(1 - S['trim_reserve']) * 100:.0f} % of roll authority in reserve before it accepts sideslip.")
    w("")
    # ------------------------------------------------------- components
    w("## 2. Damage components, hitboxes and what they affect")
    w("")
    w("Hitbox: centre (x left, s aft of the nose, z up) and half sizes in metres; yaw about z and roll "
      "about the length axis in degrees. Boxes of internal parts (engine, cockpit, fuel feed, power "
      "system) are defined from the public layout; all others are fitted to the mesh.")
    w("")
    w("| Component | HP | Breaks off | Hitbox centre | Half size | Yaw / roll | Affects |")
    w("|---|---|---|---|---|---|---|")
    for k, c in d.COMPONENTS.items():
        h = hb.get(k)
        cen = ", ".join(f"{v:.2f}" for v in h["centre"]) if h else "–"
        half = ", ".join(f"{v:.2f}" for v in h["half"]) if h else "–"
        yr = f"{h['yaw_deg']:.0f} / {h['roll_deg']:.0f}" if h else "–"
        w(f"| `{k}` {c['label']} | {c['hp']} | {'yes' if c.get('detach') else ''} | {cen} | {half} | {yr} | {affects(k, c)} |")
    w("")
    w("**Hits.** A point hit gives 70 % of its damage to the smallest box that contains the point and shares "
      "the rest between the other boxes there. A blast loses damage linearly with the distance to each box. "
      "A part that breaks off takes its children with it (outer wing, LEF and flaperon go with the inner wing).")
    w("")
    w("**Wing split measured on the mesh:** the outer panel (outboard of the tear line) carries "
      f"{d.OUTER_SHARE * 100:.1f} % of one wing's lift at {d.OUTER_ARM:.2f} m from the centreline; "
      f"the inner panel acts at {d.ROOT_ARM:.2f} m. Body lift is {d.BODY_LIFT * 100:.0f} % of the total.")
    w("")
    # -------------------------------------------------------- formulas
    w("## 3. How damage changes the attributes")
    w("")
    w("- **Thrust** = intact thrust × engine^1.2 (0 below 15 % = flame-out) × (mean inlet airflow)^1.3 × "
      "(0.8 + 0.2 × nozzle) × 0.5 if the fuel feed is below 25 %. The afterburner needs nozzle > 50 % and engine > 40 %.")
    w("- **Max speed** = lowest of: thrust = drag (drag polar with transonic rise, more drag from holes and "
      "missing parts, more induced drag when lift is lost), the Mach placard of damaged surfaces, the structure, "
      "and the 700 KCAS dynamic-pressure limit (reduced when parts are missing).")
    w("- **Lift and tilt.** Missing or damaged lifting surfaces shift the lift centre sideways; lost structure "
      "and leaked fuel shift the centre of mass. The flight control system trims the rolling moment with up to "
      f"{S['trim_reserve'] * 100:.0f} % of its roll authority, then with sideslip (dihedral effect). A sideslip "
      "makes a side force, and to fly straight the jet must bank against it: tan φ = |CYβ| β / CL. "
      "That bank is the **tilt**, always towards the damaged side. If even full control and 8° of sideslip "
      "cannot hold the moment, the aircraft rolls off at p = ΔCl / |Clp| × 2V / b.")
    w("- **Lower speed means more tilt**, because the lift asymmetry grows with CL while the control power does not.")
    w("- **g-limit** from structure health and pitch authority (stabilators); **AoA limit** from fin health (Cnβ).")
    w("- **Fuel**: a damaged tank leaks 55 × damage^1.5 × √(capacity / 1600) kg/min; a tank in a part that "
      "breaks off is lost at once. The engine burn is drawn evenly from all tanks, so leaks create a lateral imbalance.")
    w("- **Systems**: radar, EOTS, DAS, avionics, gun, weapons, gear, canopy, pilot, electrical power. A failed "
      "power and thermal management system leaves the actuators on battery (60 % roll authority).")
    w("")
    # -------------------------------------------------------- scenarios
    w("## 4. Damage scenarios (Mach 0.8 at 6 km unless noted)")
    w("")
    w("| Scenario | Thrust | Max Mach 11 km | Max Mach SL | g limit | Tilt | Roll-off | Min control speed | Fuel / endurance | Lost |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for n in d.SCENARIOS:
        r = d.run_scenario(n)
        tilt = "–" if r["tilt_bank_deg"] is None else (
            f"{r['tilt_bank_deg']:.1f}° {r['tilt_towards']}" if r["tilt_bank_deg"] > 0 else "0°")
        ro = f"{r['roll_off_rate_deg_s']:.0f}°/s" if r["roll_off_rate_deg_s"] else "–"
        lost = [s for s, v in r["systems"].items() if v is False and s not in ("fire",)]
        if r["systems"].get("fire"):
            lost.append("FIRE")
        if r["missing_parts"]:
            lost.append("parts: " + ", ".join(r["missing_parts"]))
        ga = r["ground_attitude"]
        if ga["roll_deg"] or ga["pitch_deg"]:
            lost.append(f"on the ground: roll {ga['roll_deg']:+.1f}°, pitch {ga['pitch_deg']:+.1f}°")
        mins = d.SCENARIO_MINUTES.get(n)
        fuel = f"{r['fuel_kg']} kg / {r['endurance_min']} min" + (f" (after {mins:.0f} min)" if mins else "")
        w(f"| {n.replace('_', ' ')} | {r['thrust_percent']} % | {fmt(r['max_mach_11km'])} ({r['max_mach_11km_limited_by']}) | "
          f"{fmt(r['max_mach_SL'])} | {r['g_limit']} | {tilt} | {ro} | {fmt(r['v_min_control_kt_SL'])} kt | {fuel} | "
          f"{'; '.join(lost) or '–'} |")
    w("")
    # -------------------------------------------------- tilt vs speed
    w("## 5. Tilt against airspeed after losing a wing (sea level)")
    w("")
    speeds = [180, 200, 225, 250, 275, 300, 350, 400, 450, 500, 600]
    for scen, title in (("outer_left_wing_lost", "Outer left wing panel missing"),
                        ("left_wing_lost", "Whole left wing missing")):
        w(f"**{title}**")
        w("")
        w("| Airspeed | CL needed | Rolling moment ΔCl | Roll control used | Sideslip | Tilt (bank) | Result |")
        w("|---|---|---|---|---|---|---|")
        for kt in speeds:
            r = d.run_scenario(scen, kt_to_mach_sl(kt), 0.0)
            if r["controllable"]:
                res = "holds straight flight"
                tilt = (f"{r['tilt_bank_deg']:.1f}° {r['tilt_towards']} wing down" if r["tilt_bank_deg"] >= 0.05
                        else "0° (wings level)")
            else:
                res = f"rolls off at {r['roll_off_rate_deg_s']:.0f}°/s"
                tilt = "–"
            w(f"| {kt} kt | {r['required_CL']:.3f} | {r['asymmetric_Cl']:+.4f} | {r['roll_control_used'] * 100:.0f} % | "
              f"{r['sideslip_deg']:.1f}° | {tilt} | {res} |")
        w("")
    v_outer = d.run_scenario("outer_left_wing_lost")["v_min_control_kt_SL"]
    v_whole = d.run_scenario("left_wing_lost")["v_min_control_kt_SL"]

    def vtxt(v):
        return "cannot be held at any speed" if v is None else f"can be held down to about {v:.0f} kt"

    w(f"With the outer panel gone the jet {vtxt(v_outer)}; with the whole wing gone it {vtxt(v_whole)}. "
      "The tilt peaks just above the minimum control speed and fades as speed rises, because less lift "
      "(and so less lift asymmetry) is needed. For comparison, the IAF F-15D that landed without most of "
      "its right wing in 1983 was flown fast for the same reason.")
    w("")
    # -------------------------------------------------- engine damage
    w("## 6. Engine damage and maximum speed")
    w("")
    w("| Thrust available | Max Mach 11 km | Max speed 11 km | Max Mach SL | Dry max Mach 11 km |")
    w("|---|---|---|---|---|")
    for th in (1.0, 0.9, 0.8, 0.7, 0.6, 0.5, 0.4, 0.3):
        st = d.intact_state()
        st["engine"] = th ** (1 / 1.2)
        r = d.evaluate(st)
        w(f"| {th * 100:.0f} % | {fmt(r['max_mach_11km'], 3)} ({r['max_mach_11km_limited_by']}) | "
          f"{fmt(r['max_speed_kmh_11km'])} km/h | {fmt(r['max_mach_SL'], 3)} ({r['max_mach_SL_limited_by']}) | "
          f"{fmt(r['max_mach_dry_11km'], 3)} |")
    w("")
    # -------------------------------------------------- gear collapse
    w("## 7. Landing-gear collapse on the ground")
    w("")
    w("Measured on the mesh: the jet pivots about the line through the two tyres that still stand until "
      "the first part of the airframe touches the ground.")
    w("")
    w("| Broken leg | Roll | Pitch | Rotation | First contact (x, s, z) |")
    w("|---|---|---|---|---|")
    for k, g in d.GROUND_ATTITUDE.items():
        tp = ", ".join(f"{v:.2f}" for v in g.get("touch_point_xsz", []))
        w(f"| {k} | {g['roll_deg']:+.1f}° | {g['pitch_deg']:+.1f}° | {g['angle_deg']:.1f}° | {tp} |")
    w("")
    w("Roll is positive with the left wing down, pitch positive nose up.")
    w("")
    # -------------------------------------------------- usage
    w("## 8. Using it")
    w("")
    w("**Command line (no Blender):**")
    w("")
    w("```")
    w("python3 scripts/damage/f35_damage.py --list")
    w("python3 scripts/damage/f35_damage.py --scenario outer_left_wing_lost --mach 0.4 --alt 0")
    w("python3 scripts/damage/f35_damage.py --set engine=0.5 inlet_R=0.3 --mach 0.9 --alt 9000")
    w("python3 scripts/damage/f35_damage.py --blast 1.2 9.5 0.3 400 3.0      # x s z HP radius")
    w("python3 scripts/damage/f35_damage.py --all")
    w("```")
    w("")
    w("**In Blender** (after building with `scripts/build_f35i.py`):")
    w("")
    w("- Set or keyframe `F35I_Rig[\"health_<component>\"]` (0..1). Soot, smoke, fuel vapour and the folded "
      "gear leg follow at once; a part whose health reaches 0 is replaced by its torn stub.")
    w("- To make a part break off and tumble away at frame F, also set `break_frame_<component>` = F "
      "(or call `f35.destruct.break_off(component, F)`). Set `debris_ground` = 1 when parked, so the "
      "pieces fall onto the apron instead of streaming aft.")
    w("- `f35.destruct.impact(origin, direction, hp, frame)` ray-casts a hit, adds a scorch mark with glowing "
      "edges and lowers the health of the components inside the hitboxes. `blast(centre, hp, radius, frame)` "
      "does the same for a proximity blast.")
    w("- `f35.destruct.flight_response(frame, mach, alt)` runs the simulator on the current health and keys "
      "the bank (tilt), the sideslip and the side-stick, or a continuous roll if the jet cannot be held.")
    w("- `f35.destruct.collapse_gear(\"main_gear_L\", frame)` drops the jet onto its wing using the measured attitude.")
    w("")
    w("**Other tools:** `data/damage_model.json` holds the specification, every component with its hitbox, "
      "the wing split, the gear-collapse attitudes and the intact attributes.")
    w("")
    w("## 9. Limits")
    w("")
    w("This is an engineering-style model for animation and games, not flight-test data. Aerodynamic and "
      "control coefficients are typical values, not F-35 data; the structure, armour-free hit points and leak "
      "rates are invented but consistent. The trends (tilt grows as speed drops, a damaged inlet or engine "
      "caps the speed, a lost fin lowers the AoA limit) follow standard flight mechanics.")
    w("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    print("wrote", OUT, len(L), "lines")


if __name__ == "__main__":
    main()
